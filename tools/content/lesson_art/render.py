#!/usr/bin/env python3
"""Render the v2 lesson word illustrations (imageChoice art).

    python3 tools/content/lesson_art/render.py [--course vi_en] [--only word,word] [--sheet out.png]

Reads every image asset (`i.*`) the built course references (content/<course>/dist/v2/bundles),
draws it with the kit in this folder, and writes
  content/<course>/media/images/src/<fileId>.svg   vector source (palette colours only)
  content/<course>/media/images/<fileId>.webp      512x512 lossless WebP, transparent background
  apps/mobile/assets/lesson_images/<fileId>.webp   same bytes, bundled for the mock / offline app
fileId = i.<unitId>.<wordId> (EXERCISE_FORMATS.md section 5). Requires cairosvg + Pillow
(`pip install cairosvg`; on this workspace PYTHONPATH=/workspace/tools/pylib). Also writes
apps/mobile/lib/features/learning/data/lesson_image_catalog.g.dart (fileId -> sha256).
The generator (tools/content/build-course.mjs) hashes the committed WebP bytes, so re-running
this only changes a manifest when the drawing changes.
"""
import argparse
import io
import json
import os
import re
import sys
from multiprocessing import Pool

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, HERE)

import cairosvg  # noqa: E402
from PIL import Image  # noqa: E402

from kit import svg  # noqa: E402
from concepts_a import ART as ART_A  # noqa: E402
from concepts_b import ART as ART_B  # noqa: E402

ART = {**ART_A, **ART_B}


def picturable(course):
    """(fileId, wordId) for every image asset the built course references (dist/v2 bundles)."""
    bundles = os.path.join(ROOT, 'content', course, 'dist', 'v2', 'bundles')
    ids = set()
    for name in os.listdir(bundles):
        for asset in json.load(open(os.path.join(bundles, name), encoding='utf8')).get('assets', []):
            if asset['fileId'].startswith('i.'):
                ids.add(asset['fileId'])
    return [(f, f.split('.')[-1]) for f in sorted(ids)]


def draw(job):
    file_id, word_id, media, bundled = job
    source = svg(ART[word_id]())
    open(os.path.join(media, 'src', f'{file_id}.svg'), 'w', encoding='utf8').write(source)
    png = cairosvg.svg2png(bytestring=source.encode(), output_width=512, output_height=512)
    image = Image.open(io.BytesIO(png)).convert('RGBA')
    buf = io.BytesIO()
    image.save(buf, 'WEBP', lossless=True, quality=100, method=4, exact=False)
    data = buf.getvalue()
    for d in (media, bundled):
        open(os.path.join(d, f'{file_id}.webp'), 'wb').write(data)
    return file_id, image


def write_catalog(bundled):
    """Dart map of the images shipped with the app: fileId -> sha256 of the bundled bytes."""
    import hashlib
    rows = []
    for name in sorted(os.listdir(bundled)):
        if name.endswith('.webp'):
            digest = hashlib.sha256(open(os.path.join(bundled, name), 'rb').read()).hexdigest()
            rows.append(f"  '{name[:-5]}':\n      '{digest}',")
    out = os.path.join(ROOT, 'apps', 'mobile', 'lib', 'features', 'learning', 'data', 'lesson_image_catalog.g.dart')
    open(out, 'w', encoding='utf8').write(
        '// GENERATED by tools/content/lesson_art/render.py. Do not edit.\n'
        '// Word illustrations bundled under assets/lesson_images/<fileId>.webp:\n'
        '// fileId -> sha256 of the bundled bytes (equals the content manifest hash).\n\n'
        'const bundledLessonImages = <String, String>{\n' + '\n'.join(rows) + '\n};\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--course', default='vi_en')
    ap.add_argument('--only', default='')
    ap.add_argument('--sheet', default='')
    args = ap.parse_args()
    only = set(filter(None, args.only.split(',')))
    words = picturable(args.course)
    media = os.path.join(ROOT, 'content', args.course, 'media', 'images')
    bundled = os.path.join(ROOT, 'apps', 'mobile', 'assets', 'lesson_images')
    for d in (os.path.join(media, 'src'), bundled):
        os.makedirs(d, exist_ok=True)
    missing = [w for _, w in words if w not in ART]
    if missing:
        sys.exit(f'no drawing for: {", ".join(missing)}')
    jobs = [(f, w, media, bundled) for f, w in words if not only or w in only]
    with Pool(min(8, os.cpu_count() or 1)) as pool:
        tiles = pool.map(draw, jobs)
    write_catalog(bundled)
    if args.sheet:
        cols = 10
        rows = (len(tiles) + cols - 1) // cols
        sheet = Image.new('RGBA', (cols * 160, rows * 160), 'white')
        for i, (_, im) in enumerate(tiles):
            sheet.paste(im.resize((150, 150)), ((i % cols) * 160 + 5, (i // cols) * 160 + 5), im.resize((150, 150)))
        sheet.convert('RGB').save(args.sheet)
    print(f'{len(tiles)} images -> {os.path.relpath(media, ROOT)} + {os.path.relpath(bundled, ROOT)}')


if __name__ == '__main__':
    main()
