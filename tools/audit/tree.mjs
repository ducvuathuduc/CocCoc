import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
// Refreshes the generated block of the canonical layout doc; prose outside the markers is
// hand-maintained. `--check` exits 1 when the block is stale.
const output = 'docs/agent/REPOSITORY_TREE.md';
const BEGIN = '<!-- tree:begin (generated by `pnpm docs:tree`; do not edit) -->';
const END = '<!-- tree:end -->';
const files = [...new Set(execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '-z'], { cwd: root, encoding: 'utf8' }).split('\0').filter((file) => file && fs.existsSync(path.join(root, file))))].sort();
const tree = { children: new Map(), count: 0 };
for (const file of files) {
  let current = tree;
  current.count++;
  for (const part of file.split('/')) {
    if (!current.children.has(part)) current.children.set(part, { children: new Map(), count: 0 });
    current = current.children.get(part);
    current.count++;
  }
}
const lines = ['CocEnglish/'];
function render(node, prefix = '', depth = 0) {
  const entries = [...node.children].sort(([a], [b]) => a.localeCompare(b));
  entries.forEach(([name, child], index) => {
    const last = index === entries.length - 1;
    const directory = child.children.size > 0;
    lines.push(`${prefix}${last ? '└── ' : '├── '}${name}${directory ? '/' : ''}${directory && depth >= 2 ? ` (${child.count} files; collapsed)` : ''}`);
    if (directory && depth < 2) render(child, `${prefix}${last ? '    ' : '│   '}`, depth + 1);
  });
}
render(tree);
const doc = fs.readFileSync(path.join(root, output), 'utf8');
const start = doc.indexOf(BEGIN);
const end = doc.indexOf(END);
if (start < 0 || end < start) throw new Error(`${output}: tree markers missing`);
const block = `${BEGIN}\n\nGenerated from Git-tracked and unignored files on disk. Directories below depth three are collapsed with file counts. Total: ${files.length} files.\n\n\`\`\`text\n${lines.join('\n')}\n\`\`\`\n\n`;
const next = doc.slice(0, start) + block + doc.slice(end);
if (process.argv.includes('--check')) {
  if (next !== doc) {
    console.error(`${output} tree block is stale: run \`pnpm docs:tree\`.`);
    process.exit(1);
  }
} else fs.writeFileSync(path.join(root, output), next);
console.log(JSON.stringify({ status: 'PASS', files: files.length, output, source: 'Git-tracked/unignored existing paths on disk' }));
