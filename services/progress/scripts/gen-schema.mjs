// Regenerates services/progress/src/persistence/schema.ts from appwrite/schema/foundation.json
// (p_ tables only), formatted with the repository Prettier config. Drift is caught by
// services/progress/test/schema.test.mjs, which compares PROGRESS_SCHEMA with foundation.json.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const out = path.join(root, 'services/progress/src/persistence/schema.ts');

export function progressSchemaSource() {
  const foundation = JSON.parse(
    fs.readFileSync(path.join(root, 'appwrite/schema/foundation.json'), 'utf8'),
  );
  const lines = [
    '// GENERATED by services/progress/scripts/gen-schema.mjs from appwrite/schema/foundation.json.',
    '// Do not edit by hand. The Progress adapters validate every staged row against this table.',
    "export type ColumnType = 'string' | 'integer' | 'boolean' | 'datetime' | 'enum';",
    'export interface ColumnSpec {',
    '  type: ColumnType;',
    '  required: boolean;',
    '  size?: number;',
    '  min?: number;',
    '  max?: number;',
    '  elements?: readonly string[];',
    '}',
    'export interface TableSpec {',
    '  mutable: boolean;',
    '  columns: Readonly<Record<string, ColumnSpec>>;',
    '}',
    'export const PROGRESS_SCHEMA = {',
  ];
  for (const table of foundation.tables.filter((t) => t.owner === 'progress')) {
    lines.push(`  ${table.id}: {`, `    mutable: ${Boolean(table.mutable)},`, '    columns: {');
    for (const c of table.columns) {
      const spec = { type: c.type, required: c.required !== false };
      if (c.size !== undefined) spec.size = c.size;
      if (c.min !== undefined) spec.min = c.min;
      if (c.max !== undefined) spec.max = c.max;
      if (c.elements) spec.elements = c.elements;
      lines.push(`      ${c.key}: ${JSON.stringify(spec).replace(/"(\w+)":/g, '$1: ')},`);
    }
    lines.push('    },', '  },');
  }
  lines.push('} as const satisfies Record<string, TableSpec>;', '');
  return lines.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const prettier = await import('prettier');
  const options = (await prettier.resolveConfig(out)) ?? {};
  fs.writeFileSync(
    out,
    await prettier.format(progressSchemaSource(), { ...options, filepath: out }),
  );
}
